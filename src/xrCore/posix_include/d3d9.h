// macOS stand-in for the Windows header of the same name.
// Engine and game code outside the renderer only use Direct3D 9 types and constants
// (colours, primitive types, vertex formats, a few render states) as plain data.
// Nothing here talks to a GPU; the macOS renderer is a separate stage of the port.
#pragma once
#include "d3d9types.h"
#include "ole2.h"

